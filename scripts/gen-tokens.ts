import { createLobeToken } from '@lobehub/ui';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Token = Record<string, unknown>;

const root = join(import.meta.dirname, '..');
const pkg = JSON.parse(readFileSync(join(root, 'node_modules', '@lobehub', 'ui', 'package.json'), 'utf8')) as {
  version: string;
};

const METRIC = /^(borderRadius(XS|SM|LG)?|fontSize(SM|LG|XL|Heading[1-5])?|controlHeight(XS|SM|LG)?|lineWidth|fontWeightStrong)$/;

const light = createLobeToken({ appearance: 'light' }) as Token;
const dark = createLobeToken({ appearance: 'dark' }) as Token;

const parseColor = (value: string): [number, number, number, number] | undefined => {
  const v = value.trim().toLowerCase();
  if (v === 'transparent') return [0, 0, 0, 0];
  let m = /^#([0-9a-f]{3})$/.exec(v);
  if (m) {
    const [r, g, b] = [...m[1]].map((c) => Number.parseInt(c + c, 16));
    return [r, g, b, 1];
  }
  m = /^#([0-9a-f]{6})([0-9a-f]{2})?$/.exec(v);
  if (m) {
    const n = (i: number) => Number.parseInt(m![1].slice(i, i + 2), 16);
    return [n(0), n(2), n(4), m[2] ? Number.parseInt(m[2], 16) / 255 : 1];
  }
  m = /^rgba?\(([^)]+)\)$/.exec(v);
  if (m) {
    const parts = m[1].split(/[\s,/]+/).filter(Boolean).map(Number);
    if (parts.length >= 3 && parts.every(Number.isFinite)) {
      return [parts[0], parts[1], parts[2], parts[3] ?? 1];
    }
  }
  return undefined;
};

const goColor = ([r, g, b, a]: [number, number, number, number]) =>
  a === 1 ? `ui.RGB(${r}, ${g}, ${b})` : `ui.RGBA(${r}, ${g}, ${b}, ${a})`;

const fieldName = (key: string) => {
  const name = key.startsWith('color') ? key.slice('color'.length) : key;
  return name[0].toUpperCase() + name.slice(1);
};

const PRESETS = ['red', 'volcano', 'orange', 'gold', 'yellow', 'lime', 'green', 'cyan', 'blue', 'geekblue', 'purple', 'magenta', 'gray'];

const EXTRA_COLORS = new Set([
  'yellow9',
  'geekblue8', 'geekblue9', 'gray7', 'gray9', 'gray10', 'gray11', 'magenta8', 'magenta9',
  'orange9', 'purple8', 'purple9', 'volcano8', 'volcano9',
  ...PRESETS.flatMap((p) => [p, `${p}Active`, `${p}FillTertiary`, `${p}FillQuaternary`]),
]);

const colorKeys = Object.keys(light)
  .filter((k) => (k.startsWith('color') || EXTRA_COLORS.has(k)) && typeof light[k] === 'string')
  .filter((k) => parseColor(String(light[k])) && parseColor(String(dark[k] ?? '')))
  .sort();
const metricKeys = Object.keys(light)
  .filter((k) => METRIC.test(k) && typeof light[k] === 'number')
  .sort();

// Derived colors are roles Lobe UI fills from another token rather than
// naming, kept as fields so an app can set them apart from their source.
// PrimaryForeground is the text and glyphs on a solid Primary surface: Lobe UI
// uses the layout background, and an app whose primary is saturated sets it to
// TextLightSolid.
const DERIVED: Record<string, string> = {
  primaryForeground: 'colorBgLayout',
};

const derivedKeys = Object.keys(DERIVED).sort();
for (const k of derivedKeys) {
  if (!colorKeys.includes(DERIVED[k])) throw new Error(`derived ${k}: missing source ${DERIVED[k]}`);
  light[k] = light[DERIVED[k]];
  dark[k] = dark[DERIVED[k]];
}
colorKeys.push(...derivedKeys);
colorKeys.sort();

const fields = [...colorKeys, ...metricKeys].map(fieldName);
const duplicate = fields.find((f, i) => fields.indexOf(f) !== i);
if (duplicate) throw new Error(`token field collision: ${duplicate}`);

const pad = Math.max(...fields.map((f) => f.length));

const struct = [
  `\t${'Dark'.padEnd(pad)} bool`,
  ...colorKeys.map((k) => `\t${fieldName(k).padEnd(pad)} ui.Color`),
  ...metricKeys.map((k) => `\t${fieldName(k).padEnd(pad)} float32`),
].join('\n');

const values = (token: Token, isDark: boolean) =>
  [
    `\t${'Dark:'.padEnd(pad + 1)} ${isDark},`,
    ...colorKeys.map((k) => `\t${(fieldName(k) + ':').padEnd(pad + 1)} ${goColor(parseColor(String(token[k]))!)},`),
    ...metricKeys.map((k) => `\t${(fieldName(k) + ':').padEnd(pad + 1)} ${token[k]},`),
  ].join('\n');

const semanticKeys = colorKeys.filter((k) => !EXTRA_COLORS.has(k));

const names = semanticKeys.map((k) => `\t${JSON.stringify(fieldName(k))},`).join('\n');

const cases = colorKeys
  .map((k) => `\tcase ${JSON.stringify(fieldName(k))}:\n\t\treturn t.${fieldName(k)}, true`)
  .join('\n');

const source = `// Code generated by scripts/gen-tokens.ts from @lobehub/ui ${pkg.version}. DO NOT EDIT.

package theme

import "github.com/egoist/mygo/ui"

type Tokens struct {
${struct}
}

var lightTokens = Tokens{
${values(light, false)}
}

var darkTokens = Tokens{
${values(dark, true)}
}

var colorTokenNames = []string{
${names}
}

func (t *Tokens) Color(name string) (ui.Color, bool) {
\tswitch name {
${cases}
\t}
\treturn ui.Color{}, false
}
`;

const out = join(root, 'pkg', 'theme', 'tokens_gen.go');
writeFileSync(out, source);
execFileSync('gofmt', ['-w', out]);
console.log(`wrote ${colorKeys.length} colors and ${metricKeys.length} metrics to tokens_gen.go`);
